package com.example.controllerornot

import java.nio.ByteBuffer
import java.nio.ByteOrder

/** Identity the phone presents to the host (name + Device Information service + PnP ID). */
enum class HidProfile(
    val label: String,
    val deviceName: String,
    val manufacturer: String,
    val model: String,
    val vendorId: Int,
    val productId: Int,
    val version: Int,
) {
    XBOX_SERIES(
        "Xbox Series controller (BLE)", "Xbox Wireless Controller", "Microsoft",
        "Xbox Wireless Controller", 0x045E, 0x0B13, 0x0903,
    ),
    XBOX_ONE_S(
        "Xbox One S controller (BT)", "Xbox Wireless Controller", "Microsoft",
        "Xbox Wireless Controller", 0x045E, 0x02FD, 0x0903,
    ),
    GENERIC(
        "Generic gamepad (no spoofing)", "Android Gamepad", "Controller or Not",
        "Virtual Gamepad", 0x1209, 0x0001, 0x0100,
    );

    /** PnP ID characteristic value (0x2A50): vendor-ID source 0x02 = USB-IF, then VID, PID, version (LE). */
    fun pnpId(): ByteArray = ByteBuffer.allocate(7).order(ByteOrder.LITTLE_ENDIAN)
        .put(0x02)
        .putShort(vendorId.toShort())
        .putShort(productId.toShort())
        .putShort(version.toShort())
        .array()
}

object HidReport {
    const val INPUT_REPORT_ID = 1
    const val OUTPUT_REPORT_ID = 3
    const val INPUT_REPORT_SIZE = 16

    /** HID report map laid out like the Xbox wireless controller: report 1 = input, report 3 = rumble. */
    val REPORT_MAP: ByteArray = intArrayOf(
