        0x09, 0x70, 0x15, 0x00, 0x25, 0x64, 0x75, 0x08, 0x95, 0x04, 0x91, 0x02,   // magnitudes x4
        0x09, 0x50, 0x66, 0x01, 0x10, 0x55, 0x0E, 0x15, 0x00, 0x26, 0xFF, 0x00,
        0x75, 0x08, 0x95, 0x01, 0x91, 0x02,                                       // duration
        0x09, 0xA7, 0x91, 0x02,                                                   // start delay
        0x65, 0x00, 0x55, 0x00, 0x09, 0x7C, 0x91, 0x02,                           // loop count
        0xC0,
        0xC0,
    ).map { it.toByte() }.toByteArray()

    private fun axis(v: Float): Int = (((v.coerceIn(-1f, 1f) + 1f) / 2f) * 65535f).toInt()
    private fun trigger(v: Float): Int = (v.coerceIn(0f, 1f) * 1023f).toInt()

    /** Builds the 16-byte input report (without the report ID, as HID-over-GATT requires). */
    fun build(s: GamepadState): ByteArray {
        val b = ByteBuffer.allocate(INPUT_REPORT_SIZE).order(ByteOrder.LITTLE_ENDIAN)
        b.putShort(axis(s.lx).toShort())
        b.putShort(axis(s.ly).toShort())
        b.putShort(axis(s.rx).toShort())
        b.putShort(axis(s.ry).toShort())
        b.putShort(trigger(s.lt).toShort())
        b.putShort(trigger(s.rt).toShort())
        b.put((s.hat and 0x0F).toByte())
        b.putShort((s.buttons and 0x7FFF).toShort())
        b.put(0)                                                   // Share button + padding
        return b.array()
    }
}
